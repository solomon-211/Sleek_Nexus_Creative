// Builds src/icons.generated.css — a stylesheet containing ONLY the Font
// Awesome icons this app actually references, as inline SVG masks.
//
// Why: the site used to load Font Awesome's complete stylesheet plus its
// solid and brands webfonts from a CDN — a render-blocking third-party
// request and a few hundred KB of glyphs to draw the ~100 icons in use. That
// cost lands hardest on exactly the slow mobile connections this site is
// built for. This script keeps the markup unchanged (`<i className="fas
// fa-check" />` still works, including dynamic `fas ${icon}` class strings)
// and swaps the delivery: each used icon becomes one CSS rule whose mask is
// the icon's SVG path, painted with `currentColor` so Tailwind text-color and
// text-size utilities keep working exactly as they did with the webfont.
//
// It runs automatically via the Vite plugin in vite.config.js (on dev server
// start, on source changes, and on build), so there is nothing to remember —
// use a new `fa-*` class anywhere under src/ and it is picked up.
//
// An unknown icon name fails the build rather than rendering as a blank box.

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { dirname, join, extname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { fas } from '@fortawesome/free-solid-svg-icons'
import { fab } from '@fortawesome/free-brands-svg-icons'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const SRC_DIR = join(ROOT, 'src')
const OUT_PATH = join(SRC_DIR, 'icons.generated.css')

// Font Awesome utility classes that share the `fa-` prefix but aren't icons.
const MODIFIERS = new Set(['fa-spin', 'fa-fw'])

const TOKEN_RE = /\bfa-[a-z0-9]+(?:-[a-z0-9]+)*\b/g

// name -> [width, height, path], covering every alias Font Awesome ships
// (so both `fa-location-dot` and its v5 name `fa-map-marker-alt` resolve).
function buildLookup() {
  const lookup = new Map()
  // Brands first, so a solid icon wins if a name ever exists in both packs.
  for (const pack of [fab, fas]) {
    for (const def of Object.values(pack)) {
      const [width, height, aliases, , path] = def.icon
      const entry = [width, height, Array.isArray(path) ? path.join(' ') : path]
      lookup.set(def.iconName, entry)
      for (const alias of aliases) {
        if (typeof alias === 'string') lookup.set(alias, entry)
      }
    }
  }
  return lookup
}

function walk(dir) {
  const out = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walk(full))
    else if (['.js', '.jsx'].includes(extname(entry.name))) out.push(full)
  }
  return out
}

function collectUsedNames() {
  const names = new Set()
  for (const file of walk(SRC_DIR)) {
    for (const token of readFileSync(file, 'utf8').match(TOKEN_RE) || []) {
      if (!MODIFIERS.has(token)) names.add(token)
    }
  }
  return [...names].sort()
}

function maskUrl([width, height, path]) {
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${width} ${height}'><path d='${path}'/></svg>`
  // Only the characters that are unsafe inside a double-quoted CSS url().
  return `url("data:image/svg+xml,${svg.replace(/</g, '%3C').replace(/>/g, '%3E').replace(/#/g, '%23')}")`
}

export function generateIcons() {
  const lookup = buildLookup()
  const used = collectUsedNames()

  const unknown = used.filter((token) => !lookup.has(token.slice(3)))
  if (unknown.length) {
    throw new Error(`[generate-icons] Unknown Font Awesome icon(s): ${unknown.join(', ')} — check the spelling, or add it to MODIFIERS in scripts/generate-icons.mjs if it is a utility class.`)
  }

  const rules = used.map((token) => {
    const entry = lookup.get(token.slice(3))
    const [width, height] = entry
    // Width is each glyph's true aspect ratio, so icons take the same
    // horizontal space they did as font glyphs.
    return `.${token}{--fa-w:${+(width / height).toFixed(4)}em;--fa-i:${maskUrl(entry)}}`
  })

  const css = `/* GENERATED by scripts/generate-icons.mjs — do not edit. ${used.length} icons. */
.fa,.fas,.fab,.fa-solid,.fa-brands{display:inline-block;width:var(--fa-w,1em);height:1em;line-height:1;vertical-align:-0.125em;background-color:currentColor;-webkit-mask:var(--fa-i) center/contain no-repeat;mask:var(--fa-i) center/contain no-repeat}
.fa-fw{width:1.25em}
.fa-spin{animation:fa-spin 2s linear infinite}
@keyframes fa-spin{to{transform:rotate(360deg)}}
@media (prefers-reduced-motion:reduce){.fa-spin{animation-duration:6s}}
${rules.join('\n')}
`

  // Skip the write when nothing changed, so the dev-server watcher that
  // calls this on every source edit doesn't trigger a pointless CSS reload.
  if (existsSync(OUT_PATH) && readFileSync(OUT_PATH, 'utf8') === css) return { count: used.length, changed: false }
  writeFileSync(OUT_PATH, css)
  return { count: used.length, changed: true }
}

// Run directly: `node scripts/generate-icons.mjs`
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { count, changed } = generateIcons()
  console.log(`[generate-icons] ${count} icons -> src/icons.generated.css${changed ? '' : ' (unchanged)'}`)
}
